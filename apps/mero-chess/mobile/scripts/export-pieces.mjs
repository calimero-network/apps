#!/usr/bin/env node
// Export the web app's piece set (app/src/pieces.tsx, "Chessnut" by Alexis Luengas, Apache-2.0)
// for the native apps, so all three draw the same pieces:
//
//   iOS:     ios/Resources/Assets.xcassets/Pieces/<wK..bP>.imageset/<name>.svg (vector-preserving)
//   Android: android/app/src/main/res/drawable/piece_<wk..bp>.xml (VectorDrawable)
//
// The artwork is unchanged. What changes is the markup: inline `style` becomes presentation
// attributes, `display:none` elements are dropped, and (Android only) circles, ellipses and lines
// become paths, since a VectorDrawable has nothing else.
//
//   node apps/mero-chess/mobile/scripts/export-pieces.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const mobile = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(join(mobile, "../app/src/pieces.tsx"), "utf8");

const art = {};
for (const m of source.matchAll(/^\s*([wb][KQRBNP]): '(.*)',?$/gm)) art[m[1]] = m[2];
if (Object.keys(art).length !== 12) throw new Error(`expected 12 pieces, found ${Object.keys(art).length}`);

/** Every drawable element of one piece, in paint order, with its paint resolved. */
function elements(markup) {
  const out = [];
  for (const m of markup.matchAll(/<(path|circle|ellipse|line)\b([^>]*?)\/?>/g)) {
    const attrs = {};
    for (const a of m[2].matchAll(/([a-zA-Z0-9-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    if (attrs.style) {
      for (const decl of attrs.style.split(";")) {
        const [k, v] = decl.split(":").map((s) => s?.trim());
        if (k && v) attrs[k] = v;
      }
      delete attrs.style;
    }
    if (attrs.display === "none") continue;
    out.push({ tag: m[1], attrs });
  }
  return out;
}

const PAINT = ["fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "stroke-miterlimit"];
const GEOMETRY = { path: ["d"], circle: ["cx", "cy", "r"], ellipse: ["cx", "cy", "rx", "ry"], line: ["x1", "y1", "x2", "y2"] };

function svg(markup) {
  const body = elements(markup)
    .map(({ tag, attrs }) => {
      const keys = [...GEOMETRY[tag], ...PAINT].filter((k) => attrs[k] !== undefined);
      return `  <${tag} ${keys.map((k) => `${k}="${attrs[k].trim()}"`).join(" ")}/>`;
    })
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Chessnut pieces, Copyright 2015 Alexis Luengas, Apache-2.0. See THIRD_PARTY_NOTICES.md. -->\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 800" width="800" height="800">\n${body}\n</svg>\n`;
}

function pathData({ tag, attrs }) {
  const n = (k) => Number(attrs[k]);
  switch (tag) {
    case "path":
      return attrs.d.trim().replace(/\s+/g, " ");
    case "line":
      return `M${n("x1")},${n("y1")} L${n("x2")},${n("y2")}`;
    case "circle":
    case "ellipse": {
      const rx = tag === "circle" ? n("r") : n("rx");
      const ry = tag === "circle" ? n("r") : n("ry");
      const cx = n("cx");
      const cy = n("cy");
      return `M${cx - rx},${cy} a${rx},${ry} 0 1,0 ${2 * rx},0 a${rx},${ry} 0 1,0 ${-2 * rx},0 Z`;
    }
  }
}

function androidColor(value) {
  if (!value || value === "none") return null;
  const hex = value.replace("#", "");
  const six = hex.length === 3 ? hex.split("").map((c) => c + c).join("") : hex;
  return `#FF${six.toUpperCase()}`;
}

function vector(markup) {
  const paths = elements(markup)
    .map((el) => {
      const { tag, attrs } = el;
      // SVG's defaults: a shape is filled black unless told otherwise; a line has no fill at all.
      const fill = tag === "line" ? null : attrs.fill === undefined ? "#FF000000" : androidColor(attrs.fill);
      const stroke = androidColor(attrs.stroke);
      const lines = [`android:pathData="${pathData(el)}"`];
      if (fill) lines.push(`android:fillColor="${fill}"`);
      if (stroke) {
        lines.push(`android:strokeColor="${stroke}"`);
        lines.push(`android:strokeWidth="${attrs["stroke-width"] ?? 1}"`);
        if (attrs["stroke-linecap"]) lines.push(`android:strokeLineCap="${attrs["stroke-linecap"]}"`);
        if (attrs["stroke-linejoin"]) lines.push(`android:strokeLineJoin="${attrs["stroke-linejoin"]}"`);
        if (attrs["stroke-miterlimit"]) lines.push(`android:strokeMiterLimit="${attrs["stroke-miterlimit"]}"`);
      }
      return `    <path\n        ${lines.join("\n        ")} />`;
    })
    .join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Chessnut pieces, Copyright 2015 Alexis Luengas, Apache-2.0. See THIRD_PARTY_NOTICES.md. Generated by scripts/export-pieces.mjs. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="48dp"\n    android:height="48dp"\n    android:viewportWidth="800"\n    android:viewportHeight="800">\n${paths}\n</vector>\n`;
}

const catalog = join(mobile, "ios/Resources/Assets.xcassets");
const pieces = join(catalog, "Pieces");
mkdirSync(pieces, { recursive: true });
writeFileSync(join(catalog, "Contents.json"), JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2) + "\n");
writeFileSync(
  join(pieces, "Contents.json"),
  JSON.stringify({ info: { author: "xcode", version: 1 }, properties: { "provides-namespace": false } }, null, 2) + "\n",
);
const drawable = join(mobile, "android/app/src/main/res/drawable");
mkdirSync(drawable, { recursive: true });

for (const [name, markup] of Object.entries(art)) {
  const set = join(pieces, `${name}.imageset`);
  mkdirSync(set, { recursive: true });
  writeFileSync(join(set, `${name}.svg`), svg(markup));
  writeFileSync(
    join(set, "Contents.json"),
    JSON.stringify(
      {
        images: [{ filename: `${name}.svg`, idiom: "universal" }],
        info: { author: "xcode", version: 1 },
        properties: { "preserves-vector-representation": true, "template-rendering-intent": "original" },
      },
      null,
      2,
    ) + "\n",
  );
  writeFileSync(join(drawable, `piece_${name.toLowerCase()}.xml`), vector(markup));
}
console.log(`exported ${Object.keys(art).length} pieces`);
