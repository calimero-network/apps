package network.calimero.calendar.data

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.intOrNull
import network.calimero.calendar.generated.ContextContractCalling
import com.calimero.mero.app.ContextContractCalling as SdkContextContractCalling

/**
 * The generated [network.calimero.calendar.generated.CalendarClient] over the SDK's bound contract,
 * with one fix-up on the wire.
 *
 * The ABI declares `owner` and `peers` as 32-byte `bytes`, so the generated types hold them as
 * byte lists. The contract's `UserId` serialises itself as a 64-character hex string, though
 * (`logic/src/types/id.rs`). This transport converts between the two for exactly the calls that
 * carry them: the `get_events` / `get_private_events` results (hex → bytes) and the event writes'
 * `event_data.peers` (bytes → hex). Every other call passes through untouched, so large integers
 * (nanosecond timestamps) are never re-encoded.
 */
class HexIdTransport(
    private val inner: SdkContextContractCalling,
) : ContextContractCalling {
    override suspend fun query(
        method: String,
        argsJson: String,
    ): String {
        val result = inner.query(method, argsJson)
        return if (method in EVENT_VIEWS) eventsToBytes(result) else result
    }

    override suspend fun execute(
        method: String,
        argsJson: String,
    ): String {
        val args = if (method in EVENT_WRITES) peersToHex(argsJson) else argsJson
        return inner.execute(method, args)
    }

    companion object {
        val EVENT_VIEWS = setOf("get_events", "get_private_events")
        val EVENT_WRITES = setOf("create_event", "create_private_event", "update_event", "update_private_event")

        private const val BYTE_MASK = 0xff
        private const val HEX_RADIX = 16

        /** A `get_events` result with each `owner` and `peers` entry as a byte list. */
        fun eventsToBytes(json: String): String {
            val root = runCatching { Json.parseToJsonElement(json) }.getOrNull() as? JsonArray ?: return json
            return JsonArray(
                root.map { item ->
                    val obj = item as? JsonObject ?: return@map item
                    val fields = obj.toMutableMap()
                    obj["owner"]?.let { fields["owner"] = hexToBytes(it) }
                    (obj["peers"] as? JsonArray)?.let { peers -> fields["peers"] = JsonArray(peers.map(::hexToBytes)) }
                    JsonObject(fields)
                },
            ).toString()
        }

        /** Event-write arguments with `event_data.peers` as hex strings. */
        fun peersToHex(json: String): String {
            val root = runCatching { Json.parseToJsonElement(json) }.getOrNull() as? JsonObject ?: return json
            val data = root["event_data"] as? JsonObject ?: return json
            val peers = data["peers"] as? JsonArray ?: return json
            val newData = JsonObject(data + ("peers" to JsonArray(peers.map(::bytesToHex))))
            return JsonObject(root + ("event_data" to newData)).toString()
        }

        private fun hexToBytes(value: JsonElement): JsonElement {
            val hex = (value as? JsonPrimitive)?.takeIf { it.isString }?.contentOrNull ?: return value
            return JsonArray(hexBytes(hex).map { JsonPrimitive(it) })
        }

        private fun bytesToHex(value: JsonElement): JsonElement {
            val bytes = value as? JsonArray ?: return value
            val ints = bytes.map { (it as? JsonPrimitive)?.intOrNull ?: return value }
            return JsonPrimitive(ints.joinToString("") { "%02x".format(it and BYTE_MASK) })
        }

        /** The bytes of a hex string (empty when it is not hex). */
        fun hexBytes(hex: String): List<Int> {
            val clean = hex.trim().lowercase()
            if (clean.length % 2 != 0 || clean.any { it !in "0123456789abcdef" }) return emptyList()
            return clean.chunked(2).map { it.toInt(HEX_RADIX) }
        }

        /** Hex for a generated byte list. */
        fun hexOf(bytes: List<UByte>): String = bytes.joinToString("") { "%02x".format(it.toInt()) }

        /** A generated byte list for a hex id. */
        fun bytesOf(hex: String): List<UByte> = hexBytes(hex).map { it.toUByte() }
    }
}
