// Bundles the viewport (src/main.ts, which reuses the web studio's drawing code
// from ../../app/src/editor) and three.js into ONE self-contained file,
// dist/viewer.html, which both phone apps ship as a local resource. Nothing is
// loaded from a CDN at runtime.
//
//   pnpm install                      # once, at the repo root (three, fflate, vite)
//   node apps/mero-models/mobile/viewer/build.mjs
//
// esbuild is taken from the app's own vite, so this adds no dependency.
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, "../../app");
const fromApp = createRequire(join(app, "package.json"));
const fromVite = createRequire(fromApp.resolve("vite"));
const esbuild = fromVite("esbuild");

const out = await esbuild.build({
  entryPoints: [join(here, "src/main.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["safari15", "chrome90"],
  write: false,
  legalComments: "none",
  // three and fflate resolve from the app's node_modules.
  nodePaths: [join(app, "node_modules")],
  define: { "import.meta.env.VITE_PACKAGE_NAME": "undefined" },
  logLevel: "warning",
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<!-- @generated by mobile/viewer/build.mjs from mobile/viewer/src/main.ts. DO NOT EDIT. three.js is MIT licensed. -->
<style>
html, body { margin: 0; height: 100%; overflow: hidden; background: #24262b; -webkit-user-select: none; user-select: none; -webkit-touch-callout: none; }
#viewport { position: fixed; inset: 0; touch-action: none; }
canvas { display: block; width: 100%; height: 100%; touch-action: none; }
</style>
</head>
<body>
<div id="viewport"></div>
<script>${js}</script>
</body>
</html>
`;
mkdirSync(join(here, "dist"), { recursive: true });
writeFileSync(join(here, "dist/viewer.html"), html);
console.log(`dist/viewer.html: ${(html.length / 1024).toFixed(0)} KiB`);
